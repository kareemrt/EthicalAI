"""Write correct opt-out files for the categories you choose."""

import json

from .agents import CATEGORIES, SEARCH, by_category


def robots_txt(categories: list[str]) -> str:
    unknown = set(categories) - set(CATEGORIES)
    if unknown:
        raise ValueError(f"unknown category: {', '.join(sorted(unknown))}")
    if SEARCH in categories:
        raise ValueError("refusing to block search engines; edit robots.txt by hand if you mean it")
    lines = ["# --- AI crawler opt-out (generated by optout) ---"]
    for cat in categories:
        lines.append(f"# {CATEGORIES[cat]}")
        lines += [f"User-agent: {a.token}" for a in by_category(cat)]
        lines += ["Disallow: /", ""]
    return "\n".join(lines)


def tdmrep_json(policy: str | None = None) -> str:
    entry = {"location": "/*", "tdm-reservation": 1}
    if policy:
        entry["tdm-policy"] = policy
    return json.dumps([entry], indent=2) + "\n"


def html_meta() -> str:
    return ('<meta name="tdm-reservation" content="1">\n'
            '<meta name="robots" content="noai, noimageai">\n')


def headers() -> str:
    return "tdm-reservation: 1\nX-Robots-Tag: noai, noimageai\n"
