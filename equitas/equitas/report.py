"""Render an Audit as Markdown (+ SVG charts), JSON, or a terminal summary."""

from __future__ import annotations

import json
import re
from pathlib import Path

from .audit import Audit, Dimension
from .chart import impact_chart
from .metrics import ADVERSE, EXCLUDED, OK, REVIEW

BADGE = {OK: "🟢 ok", REVIEW: "🟡 review", ADVERSE: "🔴 adverse", EXCLUDED: "⚪ excluded"}
VERDICT = {
    OK: "No group falls below the impact-ratio threshold.",
    REVIEW: "Some groups fall below the threshold, but samples are too small to "
            "rule out chance. Collect more data or review the process manually.",
    ADVERSE: "At least one group falls below the threshold **and** the gap is "
             "statistically significant. This is evidence of adverse impact.",
}


def slug(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def _table(dim: Dimension, mode: str) -> list[str]:
    rate = "Scoring rate" if mode == "scoring" else "Selection rate"
    lines = [
        f"| Group | n | Share | Selected | {rate} | Impact ratio | p-value | Shortfall | Status |",
        "|---|--:|--:|--:|--:|--:|--:|--:|---|",
    ]
    for g in dim.groups:
        ir = "—" if g.impact_ratio is None else f"{g.impact_ratio:.3f}"
        p = "ref" if g.p_value is None and g.status != EXCLUDED else (
            "—" if g.p_value is None else f"{g.p_value:.3g}")
        gap = str(g.shortfall) if g.shortfall else ""
        lines.append(f"| {g.group} | {g.total} | {g.share:.1%} | {g.selected} | "
                     f"{g.rate:.1%} | {ir} | {p} | {gap} | {BADGE[g.status]} |")
    return lines


def to_markdown(audit: Audit, chart_dir: str | None = "charts") -> str:
    a = audit
    out = [
        f"# Bias audit — `{a.source}`",
        "",
        f"> **Overall: {BADGE[a.status]}** — {VERDICT[a.status]}",
        "",
        "| | |", "|---|---|",
        f"| Population | {a.population:,} |",
        f"| Outcome | `{a.outcome}` ({a.mode}) |",
        f"| Overall positive rate | {a.overall_rate:.1%} |",
    ]
    if a.median_cut is not None:
        out.append(f"| Median score cut-off | {a.median_cut:g} |")
    out += [
        f"| Impact-ratio threshold | {a.threshold:g} |",
        f"| Small-group exclusion | < {a.min_share:.0%} of population |",
        f"| Significance level | α = {a.alpha:g} |",
        "",
    ]
    for dim in a.dimensions:
        out += [f"## {dim.name.title()} — {BADGE[dim.status]}", ""]
        if chart_dir is not None:
            out += [f"![Impact ratios by {dim.name}]({chart_dir}/{slug(dim.name)}.svg)", ""]
        out += _table(dim, a.mode)
        if dim.unknown:
            out += ["", f"_{dim.unknown} people with an unknown or undisclosed "
                        f"{dim.name} were not included in this table._"]
        out.append("")
    out += [
        "## How to read this report",
        "",
        "- **Impact ratio** — a group's rate divided by the rate of the "
        "most-favoured group. Below the threshold (default 0.8, the EEOC "
        "four-fifths rule) indicates potential adverse impact.",
        "- **p-value** — two-proportion z-test against the most-favoured group "
        "(`ref`). Small values mean the gap is unlikely to be chance.",
        "- **Shortfall** — how many more people in the group would need a "
        "positive outcome to reach the threshold. A concrete size for the gap.",
        "- **Status** — 🔴 below threshold and significant · 🟡 below threshold, "
        "not significant · 🟢 at or above threshold · ⚪ too small to rate "
        "(still reported, as LL144 requires).",
        "",
        "_Generated by [Equitas](https://github.com/kareemrt/EthicalAI/tree/main/equitas). "
        "A statistical screen, not legal advice — pair it with an independent auditor "
        "where the law requires one._",
        "",
    ]
    return "\n".join(out)


def write_report(audit: Audit, out_dir: str | Path) -> Path:
    out = Path(out_dir)
    (out / "charts").mkdir(parents=True, exist_ok=True)
    for dim in audit.dimensions:
        svg = impact_chart(dim, audit.threshold)
        (out / "charts" / f"{slug(dim.name)}.svg").write_text(svg, encoding="utf-8")
    (out / "report.md").write_text(to_markdown(audit), encoding="utf-8")
    (out / "audit.json").write_text(to_json(audit), encoding="utf-8")
    return out / "report.md"


def to_json(audit: Audit) -> str:
    return json.dumps(audit.to_dict(), indent=2, ensure_ascii=False)


def to_terminal(audit: Audit, color: bool = True) -> str:
    paint = {OK: "32", REVIEW: "33", ADVERSE: "31", EXCLUDED: "90"}

    def c(text: str, status: str) -> str:
        return f"\033[{paint[status]}m{text}\033[0m" if color else text

    lines = [f"Equitas · {audit.source} · {audit.population:,} people · "
             f"{audit.mode} rate {audit.overall_rate:.1%}"]
    for dim in audit.dimensions:
        lines += ["", f"{dim.name}"]
        width = max(len(g.group) for g in dim.groups)
        for g in dim.groups:
            ir = "  —   " if g.impact_ratio is None else f"{g.impact_ratio:5.3f}"
            note = f"  needs +{g.shortfall}" if g.shortfall else ""
            lines.append(f"  {g.group:<{width}}  n={g.total:<5} rate={g.rate:6.1%}  "
                         f"IR={ir}  {c(g.status.upper(), g.status)}{note}")
    lines += ["", f"Overall: {c(audit.status.upper(), audit.status)}"]
    return "\n".join(lines)
