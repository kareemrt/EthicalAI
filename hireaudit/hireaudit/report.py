"""Render audit results as terminal text, Markdown, HTML and JSON."""
from __future__ import annotations

import json
import re
from datetime import date
from html import escape
from typing import Optional

from .charts import COLORS, impact_chart
from .data import Dataset
from .metrics import Audit

HEADERS = ("Group", "Applicants", "Positive", "Rate", "Impact ratio", "p-value", "Status")
ICONS = {"PASS": "🟢", "REVIEW": "🟡", "FAIL": "🔴", "EXCLUDED": "⚪", "N/A": "⚪"}


def slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-") or "attribute"


def _fmt(value: Optional[float], spec: str) -> str:
    return "—" if value is None else format(value, spec)


def _p(value: Optional[float]) -> str:
    if value is None:
        return "—"
    return "<0.001" if value < 0.001 else f"{value:.3g}"


def rows(audit: Audit) -> list[tuple[str, ...]]:
    ref = audit.reference
    return [(g.name + (" (ref)" if g.name == ref else ""), f"{g.n:,}", f"{g.selected:,}",
             f"{g.rate:.1%}", _fmt(g.impact_ratio, ".2f"), _p(g.p_value), g.status)
            for g in audit.groups]


def overall(audits: list[Audit]) -> str:
    return max((a.status for a in audits),
               key=("N/A", "PASS", "REVIEW", "FAIL").index, default="N/A")


def summary(ds: Dataset) -> list[str]:
    what = (f"scored above the median ({ds.cutoff:g}) on `{ds.outcome}`"
            if ds.mode == "scoring" else f"positive outcome on `{ds.outcome}`")
    return [f"{len(ds.rows):,} applicants", f"mode: {ds.mode} — {what}",
            f"overall positive rate: {ds.positive_rate:.1%}"]


# ── terminal ──────────────────────────────────────────────────────────────

def render_text(ds: Dataset, audits: list[Audit]) -> str:
    lines = ["HireAudit · " + " · ".join(s.replace("`", "") for s in summary(ds)), ""]
    for a in audits:
        table = [HEADERS, *rows(a)]
        widths = [max(len(r[i]) for r in table) for i in range(len(HEADERS))]
        lines.append(f"▸ {a.attribute}  [{a.status}]  (unknown: {a.unknown:,})")
        for r in table:
            lines.append("  " + "  ".join(c.ljust(w) if i == 0 else c.rjust(w)
                                          for i, (c, w) in enumerate(zip(r, widths))))
        lines.append("")
    lines.append(f"Overall: {overall(audits)}")
    return "\n".join(lines)


# ── markdown ──────────────────────────────────────────────────────────────

def render_markdown(ds: Dataset, audits: list[Audit], chart_dir: str = "charts") -> str:
    status = overall(audits)
    out = [f"# Bias audit report — {ICONS[status]} {status}", "",
           f"_Generated by HireAudit on {date.today():%Y-%m-%d}_", ""]
    out += [f"- {s}" for s in summary(ds)]
    a0 = audits[0]
    out += [f"- impact-ratio threshold: **{a0.threshold:g}** · significance level: "
            f"**{a0.alpha:g}** · categories under **{a0.min_share:.0%}** of data excluded", ""]
    for a in audits:
        out += [f"## {ICONS[a.status]} {a.attribute}", "",
                f"![Impact ratio by {a.attribute}]({chart_dir}/{slug(a.attribute)}.svg)", "",
                "| " + " | ".join(HEADERS) + " |",
                "|:--" + "|--:" * (len(HEADERS) - 2) + "|:-:|"]
        out += ["| " + " | ".join(r[:-1]) + f" | {ICONS[r[-1]]} {r[-1]} |" for r in rows(a)]
        out += ["", f"Applicants with unknown category: **{a.unknown:,}** "
                f"of {a.total:,}.", ""]
    out += [_LEGEND_MD]
    return "\n".join(out)


_LEGEND_MD = """## How to read this report

| Status | Meaning |
|:--|:--|
| 🔴 FAIL | Impact ratio below threshold **and** statistically significant — strong evidence of adverse impact. |
| 🟡 REVIEW | Only one signal fired: a low ratio that may be noise (small group), or a significant gap above the threshold. |
| 🟢 PASS | Neither signal fired. |
| ⚪ EXCLUDED | Category is under the minimum share of data; reported but not compared. |

An audit is evidence, not a verdict. Investigate flagged groups together with the
job-relatedness of the criteria the tool uses.
"""


# ── html ──────────────────────────────────────────────────────────────────

def render_html(ds: Dataset, audits: list[Audit]) -> str:
    status = overall(audits)
    sections = []
    for a in audits:
        body = "".join(
            "<tr>" + "".join(f"<td>{escape(c)}</td>" for c in r[:-1])
            + f'<td><span class="pill {r[-1].lower()}">{r[-1]}</span></td></tr>'
            for r in rows(a))
        sections.append(
            f'<section><h2><span class="pill {a.status.lower()}">{a.status}</span> '
            f"{escape(a.attribute)}</h2>"
            f'<div class="chart">{impact_chart(a)}</div>'
            f'<div class="scroll"><table><thead><tr>'
            + "".join(f"<th>{h}</th>" for h in HEADERS)
            + f"</tr></thead><tbody>{body}</tbody></table></div>"
            f'<p class="muted">Unknown category: {a.unknown:,} of {a.total:,} applicants.</p>'
            "</section>")
    facts = "".join(f"<li>{escape(s).replace('`', '')}</li>" for s in summary(ds))
    return _HTML.format(status=status, cls=status.lower(), facts=facts,
                        sections="".join(sections), today=date.today(),
                        **{k.lower(): v for k, v in COLORS.items()})


