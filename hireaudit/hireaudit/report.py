# ── json ──────────────────────────────────────────────────────────────────

def render_json(ds: Dataset, audits: list[Audit]) -> str:
    return json.dumps({
        "applicants": len(ds.rows), "mode": ds.mode, "outcome": ds.outcome,
        "cutoff": ds.cutoff, "positive_rate": round(ds.positive_rate, 6),
        "status": overall(audits),
        "audits": [{
            "attribute": a.attribute, "status": a.status, "reference": a.reference,
            "unknown": a.unknown, "threshold": a.threshold, "alpha": a.alpha,
            "groups": [{"name": g.name, "applicants": g.n, "positive": g.selected,
                        "rate": round(g.rate, 6), "share": round(g.share, 6),
                        "impact_ratio": None if g.impact_ratio is None else round(g.impact_ratio, 6),
                        "p_value": g.p_value, "status": g.status} for g in a.groups],
        } for a in audits],
    }, indent=2, ensure_ascii=False)
